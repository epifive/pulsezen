/**
 * Demo analytics for a public demo: three websites owned by the administrator with
 * 12 months of history (growth, seasons, weekends), goals, a weekly report, traffic alerts,
 * alert channels and a public shared dashboard, plus one small website for a few sample
 * customers (30 days).
 *
 * Every visit is generated by one model (sources, locations, devices, page flows, custom
 * events), so raw events and daily summaries follow the same definitions and the charts
 * have no step where one ends and the other begins:
 *   - the last 14 local days are stored as raw events (≤ ~12,000 rows),
 *   - older days are written straight to rollup_daily, keeping the top values of every
 *     dimension, fewer for older days (≤ ~40,000 rows in all; the rollups job then
 *     summarises the raw days on its own). Every AI assistant and the AI channel are always
 *     kept, so the AI sources add up to the AI channel on every day.
 * Kept small on purpose: remote cloud databases seed in a few round trips.
 */

