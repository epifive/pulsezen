type Caps = Record<string, number>;
const CAPS_RECENT: Caps = { page: 7, entry_page: 5, exit_page: 4, hostname: 2, event: 6, channel: 8, source: 6, referrer: 4, utm_source: 2, utm_medium: 2, utm_campaign: 2, country: 6, region: 4, city: 4, browser: 4, os: 4, device: 3, screen: 3, lang: 3 };
const CAPS_OLD: Caps = { page: 5, entry_page: 3, exit_page: 2, hostname: 2, event: 4, channel: 8, source: 4, referrer: 1, utm_source: 1, utm_medium: 1, utm_campaign: 1, country: 4, region: 1, city: 1, browser: 3, os: 2, device: 3, screen: 1, lang: 1 };
const CAPS_ARCHIVE: Caps = { page: 3, entry_page: 2, event: 2, channel: 8, source: 2, country: 2, browser: 2, os: 2, device: 2 };
const CAPS_SMALL: Caps = { page: 3, source: 3, channel: 2, country: 2, device: 2, event: 1 };
/** Days of history of the customers' websites. */
const SMALL_DAYS = 30;
/** Days ago from which the smaller caps apply (CAPS_OLD, then CAPS_ARCHIVE). */
const OLD_FROM = 30;
const ARCHIVE_FROM = 90;
/** Always kept in the source rollups (whatever the cap), so they add up to the AI channel. */
const AI_SOURCES = new Set(BASE_SOURCES.filter((s) => s.kind === "ai").map((s) => s.source));

/** Traffic by month (Jan … Dec) of each kind of website, blended between months per day. */
type Season = readonly number[];
const SEASON_SHOP: Season = [0.84, 0.8, 0.88, 0.93, 0.97, 1.02, 0.98, 0.94, 0.96, 1, 1.32, 1.28];
const SEASON_DOCS: Season = [1, 1.03, 1.06, 1.02, 0.98, 0.92, 0.84, 0.8, 0.97, 1.02, 1.03, 0.78];
const SEASON_TRAVEL: Season = [1.06, 0.94, 0.98, 1.14, 1.26, 1.12, 0.9, 0.94, 1, 1.12, 1.1, 1.22];
const SEASON_FLAT: Season = Array.from({ length: 12 }, () => 1);

function seasonOf(season: Season, day: string): number {
  const [y, m, d] = day.split("-").map(Number);
  const daysInMonth = new Date(Date.UTC(y, m, 0)).getUTCDate();
  // Month midpoints carry the monthly value; days in between blend the two nearest months.
  const pos = m - 1 + (d - 0.5) / daysInMonth - 0.5;
  const lo = Math.floor(pos);
  const f = pos - lo;
  return season[(lo + 12) % 12] * (1 - f) + season[(lo + 13) % 12] * f;
}

// ── generator ──

class Generator {
  readonly rows: EventRow[] = [];
  readonly rollups: RollupDailyTable[] = [];
  /** user id → month → [pageviews, events] */
  readonly usage = new Map<number, Map<string, [number, number]>>();

  constructor(
    private readonly rand: Rand,
    private readonly now: number,
  ) {}

  private sources(p: Profile, progress: number): W<SourceDef> {
    // AI assistants send ~5× more visitors than a year ago.
    const ai = 0.3 + 1.26 * progress ** 1.6;
    const out: Array<readonly [SourceDef, number]> = [];
    for (const s of [...BASE_SOURCES, ...p.sources]) {
      if (s.kind === "paid" && !p.paidCampaign) continue;
      const boost = p.sourceBoost[s.source] ?? 1;
      const w = s.w * boost * (s.kind === "ai" ? ai : 1);
      if (w > 0) out.push([s, w]);
    }
    return out;
  }

  private countries(p: Profile): W<string> {
    return Object.entries(GEO).map(([code, g]) => [code, g.w * (p.countryBoost[code] ?? 1)] as const);
  }

  private attrsFor(p: Profile, src: SourceDef, countries: W<string>): Attrs {
    const rand = this.rand;
    const country = pickW(rand, countries);
    const geo = GEO[country];
    const unknownCity = rand() < 0.04;
    const [region, city] = unknownCity ? ["", ""] : pickW(rand, geo.places);
    const r = rand();
    const device = r < p.mobile ? "mobile" : r < p.mobile + 0.05 ? "tablet" : "desktop";
    const os = device === "desktop" ? pickW(rand, DESKTOP_OS) : rand() < (device === "tablet" ? 0.65 : 0.46) ? "iOS" : "Android";
    const [browser, version] = pickW(rand, BROWSERS[os]);
    const utm: Utm = { utm_source: "", utm_medium: "", utm_campaign: "", utm_term: "", utm_content: "", ...src.utm };
    if (src.kind === "email" && src.source === "newsletter") Object.assign(utm, { utm_source: "newsletter", utm_medium: "email", utm_campaign: p.newsletterCampaign });
    if (src.kind === "paid") Object.assign(utm, { utm_source: "google", utm_medium: "cpc", utm_campaign: p.paidCampaign });
    return {
      source: src.source,
      channel: src.channel,
      referrer_host: src.host,
      referrer_path: src.host ? (src.source === "Reddit" ? p.subreddit : (src.path ?? "/")) : "",
      ...utm,
      country,
      region,
      city,
      browser,
      browser_version: version,
      os,
      device,
      screen: pickW(rand, SCREENS[device]),
      lang: pickW(rand, geo.langs),
    };
  }

  /** The events of one visit, starting at `start` (ms). */
  private visitEvents(p: Profile, kind: Kind, start: number): GenEvent[] {
    const rand = this.rand;
    const events: GenEvent[] = [];
    let at = start;
    const push = (name: string, path: string, gap: number, ev?: CustomEvent) => {
      const g = events.length ? Math.max(1, Math.round(gap)) : 0;
      at += g * 1000 + Math.floor(rand() * 1000);
      events.push({ name, path, at, gap: g, props: ev?.props ? JSON.stringify(ev.props) : null, revenue: ev?.revenue ?? null });
    };
    let n = rand() < BOUNCE[kind] ? 1 : pickW(rand, PAGE_COUNTS);
    let path = pickW(rand, p.landing[kind] ?? p.landing.search ?? p.pages);
    if (rand() < 0.012) {
      // A broken link: the tracker sends "404" instead of a pageview.
      push("404", pick(rand, p.notFound), 0);
      path = "/";
    }
    for (let i = 0; i < 9; i++) {
      push("pageview", path, logBetween(rand, 10, 160) * p.read);
      for (const ev of p.onPage(path, rand)) push(ev.name, path, between(rand, 3, 40), ev);
      // A bounce stays a single pageview.
      if (n === 1) break;
      const next = p.next(path, rand);
      if (next === END) break;
      if (next) n = Math.max(n, i + 2);
      if (i + 1 >= n) break;
      let browse = next;
      for (let t = 0; !browse && t < 4; t++) {
        const candidate = pickW(rand, p.pages);
        if (candidate !== path) browse = candidate;
      }
      path = browse ?? "/";
    }
    const last = events[events.length - 1].path;
    if (rand() < p.outboundRate) push("Outbound Link", last, between(rand, 4, 60), { name: "Outbound Link", props: { url: pick(rand, p.outbound) } });
    if (rand() < 0.012) push("Newsletter", last, between(rand, 5, 50), { name: "Newsletter", props: { form: "footer" } });
    return events;
  }

  /** All visits of one local day, in time order. */
  private day(p: Profile, tz: string, day: string, count: number, extra: Array<{ n: number; sources: W<SourceDef> }>, sources: W<SourceDef>, seedKey: string, live: number, recent: number): Visit[] {
    const rand = this.rand;
    const countries = this.countries(p);
    const dayStart = zonedToUtc(day, 0, tz).getTime();
    const dayEnd = zonedToUtc(addDays(day, 1), 0, tz).getTime();
    const plan: Array<{ start: number; src: SourceDef; campaign: boolean }> = [];
    const at = () => dayStart + (pickW(rand, HOURS) * 3600 + rand() * 3600) * 1000;
    for (let i = 0; i < count; i++) plan.push({ start: at(), src: pickW(rand, sources), campaign: false });
    for (const e of extra) for (let i = 0; i < e.n; i++) plan.push({ start: at(), src: pickW(rand, e.sources), campaign: true });
    // A few visits started in the last minutes, so the realtime view isn't empty.
    if (this.now >= dayStart && this.now < dayEnd) {
      for (let i = 0; i < live; i++) plan.push({ start: this.now - rand() * 200_000, src: pickW(rand, sources), campaign: false });
      // …and a few earlier today, even when the day has only just started.
      const from = Math.max(dayStart, this.now - 6 * 3_600_000);
      for (let i = 0; i < recent; i++) plan.push({ start: from + rand() * Math.max(0, this.now - 5 * 60_000 - from), src: pickW(rand, sources), campaign: false });
    }
    plan.sort((a, b) => a.start - b.start);

    const visits: Visit[] = [];
    for (const [i, v] of plan.entries()) {
      if (v.start > this.now) break;
      let sh = "";
      let attrs: Attrs | null = null;
      let kind: Kind = v.campaign ? "campaign" : v.src.kind;
      // Some visitors come back later the same day (same daily hash, new visit).
      if (visits.length > 5 && rand() < 0.07) {
        const prev = visits[Math.floor(rand() * visits.length)];
        if (prev.events[prev.events.length - 1].at < v.start - 31 * 60_000) {
          sh = prev.sh;
          attrs = { ...prev.attrs, source: "Direct / None", channel: "direct", referrer_host: "", referrer_path: "", utm_source: "", utm_medium: "", utm_campaign: "", utm_term: "", utm_content: "" };
          kind = "direct";
        }
      }
      if (!attrs) {
        sh = visitorHash(`${seedKey}:${day}:${i}`);
        attrs = this.attrsFor(p, v.src, countries);
      }
      let events = this.visitEvents(p, kind, v.start);
      // Keep the visit inside its local day.
      const overflow = events[events.length - 1].at - (dayEnd - 60_000);
      if (overflow > 0) events = events.map((e) => ({ ...e, at: e.at - overflow }));
      events = events.filter((e) => e.at <= this.now);
      if (!events.length) continue;
      visits.push({ sh, vid: visitId(`${seedKey}:${day}:${i}:v`), attrs, events });
    }
    return visits;
  }

  private addUsage(userId: number, month: string, pageviews: number, events: number): void {
    let months = this.usage.get(userId);
    if (!months) this.usage.set(userId, (months = new Map()));
    const cur = months.get(month) ?? [0, 0];
    months.set(month, [cur[0] + pageviews, cur[1] + events]);
  }

  private toRows(siteId: number, userId: number, p: Profile, visits: Visit[]): void {
    for (const v of visits) {
      for (const [i, e] of v.events.entries()) {
        const ts = new Date(e.at).toISOString();
        this.rows.push({
          site_id: siteId,
          ts,
          session_hash: v.sh,
          name: e.name,
          pathname: e.path,
          hostname: p.host(e.path),
          ...v.attrs,
          props: e.props,
          revenue_cents: e.revenue,
          visit_id: v.vid,
          gap_sec: e.gap,
          is_entry: i === 0 ? 1 : 0,
        });
        this.addUsage(userId, ts.slice(0, 7), e.name === "pageview" ? 1 : 0, e.name === "pageview" ? 0 : 1);
      }
    }
  }

  /** Daily summary rows with the same definitions as src/lib/rollups.ts, top values only. */
  private toRollups(siteId: number, userId: number, day: string, p: Profile, visits: Visit[], caps: Caps): void {
    interface Agg {
      visitors: Set<string>;
      visits: number;
      pageviews: number;
      events: number;
      bounces: number;
      duration: number;
      revenue: number;
    }
    const newAgg = (): Agg => ({ visitors: new Set(), visits: 0, pageviews: 0, events: 0, bounces: 0, duration: 0, revenue: 0 });
    const dims = new Map<string, Map<string, Agg>>();
    const get = (dim: string, value: string): Agg => {
      let m = dims.get(dim);
      if (!m) dims.set(dim, (m = new Map()));
      let a = m.get(value);
      if (!a) m.set(value, (a = newAgg()));
      return a;
    };
    const total = newAgg();
    const entryDims = ["entry_page", "source", "channel", "referrer", "utm_source", "utm_medium", "utm_campaign", "country", "region", "city", "browser", "os", "device", "screen", "lang"] as const;

    for (const v of visits) {
      let pageviews = 0;
      let events = 0;
      let duration = 0;
      let revenue = 0;
      let exit: string | null = null;
      const keys = { page: new Set<string>(), hostname: new Set<string>(), event: new Set<string>() };
      for (const [i, e] of v.events.entries()) {
        const isPageview = e.name === "pageview";
        const rev = e.revenue ?? 0;
        if (i > 0) duration += e.gap;
        revenue += rev;
        if (isPageview) {
          pageviews += 1;
          exit = e.path;
        } else events += 1;
        total.visitors.add(v.sh);
        const eventKeys: Array<[keyof typeof keys, string]> = [
          ["page", e.path],
          ["hostname", p.host(e.path)],
        ];
        if (!isPageview) eventKeys.push(["event", e.name]);
        for (const [dim, key] of eventKeys) {
          const a = get(dim, key);
          a.visitors.add(v.sh);
          if (isPageview) a.pageviews += 1;
          else a.events += 1;
          a.revenue += rev;
          keys[dim].add(key);
        }
      }
      total.pageviews += pageviews;
      total.events += events;
      total.revenue += revenue;
      const bounce = v.events.length === 1 && pageviews === 1 ? 1 : 0;
      total.visits += 1;
      total.bounces += bounce;
      total.duration += duration;
      for (const [dim, set] of Object.entries(keys)) {
        for (const key of set) {
          const a = get(dim, key);
          a.visits += 1;
          a.bounces += bounce;
          a.duration += duration;
        }
      }
      const addVisit = (a: Agg) => {
        a.visitors.add(v.sh);
        a.visits += 1;
        a.pageviews += pageviews;
        a.events += events;
        a.bounces += bounce;
        a.duration += duration;
        a.revenue += revenue;
      };
      if (exit !== null) addVisit(get("exit_page", exit));
      const entry = v.events[0];
      const values: Record<(typeof entryDims)[number], string> = { ...v.attrs, entry_page: entry.path, referrer: v.attrs.referrer_host };
      for (const dim of entryDims) addVisit(get(dim, values[dim]));
    }

    const push = (dimension: string, value: string, a: Agg) =>
      this.rollups.push({
        site_id: siteId,
        day,
        dimension,
        value,
        visitors: a.visitors.size,
        visits: a.visits,
        pageviews: a.pageviews,
        events: a.events,
        bounces: a.bounces,
        duration_sec: Math.round(a.duration),
        revenue_cents: Math.round(a.revenue),
      });
    push("total", "", total);
    for (const [dim, values] of dims) {
      const cap = caps[dim] ?? 0;
      if (!cap) continue;
      const sorted = [...values.entries()].filter(([value]) => value !== "").sort((a, b) => b[1].visitors.size - a[1].visitors.size || b[1].visits - a[1].visits || a[0].localeCompare(b[0]));
      for (const [i, [value, a]] of sorted.entries()) {
        const keep = (dim === "page" && p.keepPage?.(value)) || (dim === "source" && AI_SOURCES.has(value)) || (dim === "channel" && value === "ai");
        if (i < cap || keep) push(dim, value, a);
      }
    }
    this.addUsage(userId, day.slice(0, 7), total.pageviews, total.events);
  }

  /** History of one site: raw events for the last `rawDays` days, rollups before that. */
  site(input: { siteId: number; userId: number; spec: SiteSpec; firstDay: string; rawDays: number; small: boolean; seedKey: string }): { rolledUntil: string | null } {
    const { spec, siteId, userId } = input;
    const tz = spec.timezone;
    const today = localDay(new Date(this.now), tz);
    let rolledUntil: string | null = null;
    const season = spec.season ?? SEASON_FLAT;
    const seasonToday = seasonOf(season, today);
    for (let ago = DAYS - 1; ago >= 0; ago--) {
      const day = addDays(today, -ago);
      if (day < input.firstDay) continue;
      const progress = (DAYS - 1 - ago) / (DAYS - 1);
      const weekday = new Date(`${day}T00:00:00Z`).getUTCDay();
      const weekend = weekday === 0 || weekday === 6 ? 0.7 : weekday === 5 ? 0.92 : 1;
      // Steady growth over the year times the website's season (today's level = base).
      const level = (0.45 + 0.55 * progress) * (seasonOf(season, day) / seasonToday);
      const count = Math.max(1, Math.round(spec.base * level * weekend * between(this.rand, 0.88, 1.12)));
      const extra = spec.spikes.filter((s) => s.ago === ago).map((s) => ({ n: Math.round(count * s.extra), sources: s.sources }));
      const visits = this.day(spec.profile, tz, day, count, extra, this.sources(spec.profile, progress), input.seedKey, ago === 0 ? (spec.live ?? 0) : 0, ago === 0 ? (spec.recent ?? 0) : 0);
      if (ago < input.rawDays) this.toRows(siteId, userId, spec.profile, visits);
      else {
        const caps = input.small ? CAPS_SMALL : ago >= ARCHIVE_FROM ? CAPS_ARCHIVE : ago >= OLD_FROM ? CAPS_OLD : CAPS_RECENT;
        this.toRollups(siteId, userId, day, spec.profile, visits, caps);
        rolledUntil = day;
      }
    }
    return { rolledUntil };
  }
}

