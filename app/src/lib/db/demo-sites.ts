function pickW<T>(rand: Rand, list: W<T>): T {
  let total = 0;
  for (const [, w] of list) total += w;
  let r = rand() * total;
  for (const [v, w] of list) {
    r -= w;
    if (r < 0) return v;
  }
  return list[list.length - 1][0];
}

const pick = <T,>(rand: Rand, arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const between = (rand: Rand, min: number, max: number) => min + rand() * (max - min);
/** Log-uniform: most values near `min`, a long tail up to `max`. */
const logBetween = (rand: Rand, min: number, max: number) => Math.exp(between(rand, Math.log(min), Math.log(max)));

function token(length: number): string {
  const alphabet = "abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";
  return Array.from(crypto.randomBytes(length), (b) => alphabet[b % alphabet.length]).join("");
}

/** Deterministic ids (same shape as the ingest's): 32 hex chars per visitor, 16 base64url chars per visit. */
